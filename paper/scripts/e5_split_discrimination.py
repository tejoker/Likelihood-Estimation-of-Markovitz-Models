"""Paired alternative/boundary outcomes of the seed-combined rule in designs D1 and D2 (sec:robust).

For each replication of the power designs the rule statistic is ``pmed = min(1, 2 x median p)``
over the five synthetic seeds of the anchored relative test (Driscoll-Kraay p-values), once
against the alternative ``G* = 1.2 G0`` and once at the boundary ``G0``. This script compares the
two within each replication, at the main split (E3, 100 replications) and at the alternative split
(E5 split, 25 replications):

* paired decisions at alpha = 0.05 (both rejected, only the alternative, only the boundary,
  neither);
* the smallest boundary ``pmed`` over the replications and the largest ``pmed`` among the
  rejected alternatives;
* the number of replications whose alternative ``pmed`` lies below the smallest boundary ``pmed``
  (a size-corrected critical value at which the boundary is rejected in no replication);
* the number of replications in which the alternative ``pmed`` is below the boundary ``pmed`` of
  the same replication.

Sources: ``results/e3/e3_power_raw.csv`` (D1, main split), ``results/e3/e3_realvol_raw.csv``
(D2, main split), ``results/e5/e5_split_power_raw.csv`` (D1 and D2, alternative split).
Writes ``paper/tables/manual_e5_split_paired.tex`` and prints the numbers.

Usage (from the repository root)::

    uv run python paper/scripts/e5_split_discrimination.py
"""
from __future__ import annotations

from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[2]
E3 = ROOT / "results" / "e3"
E5 = ROOT / "results" / "e5"
OUT = ROOT / "paper" / "tables" / "manual_e5_split_paired.tex"
ALPHA = 0.05


def rule_table(raw: pd.DataFrame) -> pd.DataFrame:
    """One row per replication, columns 'alternative' and 'boundary' holding pmed."""
    t = (raw.groupby(["rep", "case"])["pvalue"]
         .apply(lambda s: min(1.0, 2.0 * float(np.median(s.to_numpy()))))
         .unstack())
    n_seeds = raw.groupby(["rep", "case"]).size()
    assert (n_seeds == 5).all(), "expected five seeds per replication and case"
    return t[["alternative", "boundary"]]


def summarise(t: pd.DataFrame) -> dict:
    a, b = t["alternative"], t["boundary"]
    ra, rb = a <= ALPHA, b <= ALPHA
    bmin = float(b.min())
    return {"reps": len(t), "both": int((ra & rb).sum()), "alt_only": int((ra & ~rb).sum()),
            "bnd_only": int((~ra & rb).sum()), "neither": int((~ra & ~rb).sum()),
            "bnd_min": bmin, "alt_rej_max": float(a[ra].max()) if ra.any() else float("nan"),
            "alt_below_bnd_min": int((a < bmin).sum()), "alt_below_bnd_same_rep": int((a < b).sum())}


def sci(x: float) -> str:
    if not np.isfinite(x):
        return "--"
    if x >= 0.001:
        return f"{x:.3f}"
    m, e = f"{x:.1e}".split("e")
    return rf"${m}\times10^{{{int(e)}}}$"


def main() -> None:
    split = pd.read_csv(E5 / "e5_split_power_raw.csv")
    cases = [("Main (E3)", "D1", pd.read_csv(E3 / "e3_power_raw.csv")),
             ("Main (E3)", "D2", pd.read_csv(E3 / "e3_realvol_raw.csv")),
             ("Alternative (E5)", "D1", split[split["design"] == "D1"]),
             ("Alternative (E5)", "D2", split[split["design"] == "D2"])]
    rows = []
    for name, design, raw in cases:
        s = summarise(rule_table(raw))
        rows.append((name, design, s))
        print(name, design, s)
    lines = [r"\begin{tabular}{llrrrrllrr}", r"\toprule",
             r" & & & \multicolumn{3}{c}{Rule at 5\%} & \multicolumn{2}{c}{$\pmed$} &"
             r" \multicolumn{2}{c}{Alternative below} \\",
             r"\cmidrule(lr){4-6} \cmidrule(lr){7-8} \cmidrule(lr){9-10}",
             r"Split & Design & Reps & both & alt.\ only & neither & min boundary"
             r" & max rej.\ alt. & min boundary & same rep. \\", r"\midrule"]
    for name, design, s in rows:
        assert s["bnd_only"] == 0, "a boundary-only rejection would need its own column"
        lines.append(f"{name} & {design} & {s['reps']} & {s['both']} & {s['alt_only']} &"
                     f" {s['neither']} & {sci(s['bnd_min'])} & {sci(s['alt_rej_max'])} &"
                     f" {s['alt_below_bnd_min']} & {s['alt_below_bnd_same_rep']} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}",
              "% generated by paper/scripts/e5_split_discrimination.py from results/e3/e3_power_raw.csv,"
              " e3_realvol_raw.csv, results/e5/e5_split_power_raw.csv"]
    OUT.write_text("\n".join(lines) + "\n")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
