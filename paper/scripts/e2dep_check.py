"""Marginal check and dependence diagnostics of the E2-dep families (Appendix C, tab:e2dep-check).

Reads ``results/e2dep/e2dep_check_mix.csv`` and ``results/e2dep/e2dep_check_block.csv`` (written by
``experiments/e2_dependence.py``) and writes ``paper/tables/manual_e2dep_check.tex``: for each
level of each family, on 20,000 simulated windows, the within-window lag-1 autocorrelation of
|r - mu|, the cross-window standard deviation of the log realised variance and the variance of the
returns (x 10^4); at the i.i.d.-marginal level the two-sample KS check of the marginal (10^6
returns of P, one per independent window, against 10^6 returns of Q).

Usage (from the repository root)::

    uv run python paper/scripts/e2dep_check.py
"""
from __future__ import annotations

import math
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[2]
SRC = {"mix": ROOT / "results" / "e2dep" / "e2dep_check_mix.csv",
       "block": ROOT / "results" / "e2dep" / "e2dep_check_block.csv"}
OUT = ROOT / "paper" / "tables" / "manual_e2dep_check.tex"
FAM_TEX = {"mix": r"(a) window mixture, $\vartheta$", "block": r"(b) block length, $L_b$"}


def num(v: float, d: int) -> str:
    if v is None or not math.isfinite(float(v)):
        return "--"
    v = float(v)
    if abs(v) < 0.5 * 10.0 ** (-d):
        v = 0.0  # print 0.000, not -0.000
    return f"{v:.{d}f}"


def main() -> None:
    lines = [r"\begin{tabular}{llrrrll}", r"\toprule",
             r"Family & Level & ACF$_1$ of $\abs{r-\mu}$ & sd of log RV & Var $\times10^4$"
             r" & KS $D$ (marginal) & KS $p$ \\", r"\midrule"]
    for fam, path in SRC.items():
        d = pd.read_csv(path, dtype={"level_label": str}).sort_values("k")
        for i, (_, r) in enumerate(d.iterrows()):
            ks_d = num(r["ks_stat"], 4) if pd.notna(r.get("ks_stat")) else ""
            ks_p = num(r["ks_pvalue"], 3) if pd.notna(r.get("ks_pvalue")) else ""
            lab = str(r["level_label"])
            if int(r["k"]) == 0:
                lab += r" ($Q=P$)"
            lines.append(" & ".join([FAM_TEX[fam] if i == 0 else "", lab,
                                     num(r["acf_abs_lag1"], 3), num(r["sd_log_rv"], 3),
                                     num(1e4 * r["var"], 2), ks_d, ks_p]) + r" \\")
        if fam == "mix":
            lines.append(r"\addlinespace[2pt]")
    lines += [r"\bottomrule", r"\end{tabular}"]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("% generated by paper/scripts/e2dep_check.py from results/e2dep/\n"
                   + "\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
