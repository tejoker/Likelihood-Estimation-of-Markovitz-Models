"""Size-adjusted power and boundary calibration of the seed-combined decision rule.

Supports the remark on calibrating BAD verdicts against the boundary replications of the power
check (Section 4.8, label rem:calibrated-bad). For each split (main: E3; alternative: E5 part
split) and design (D1, D2) it recomputes, per replication, the rule's p-value
p_med = min(1, 2 x median of the five single-seed Driscoll-Kraay p-values), separately under the
alternative (synthetic volatility x 1.2) and at the boundary, and reports

* the nominal boundary size and power of the rule (share of replications with p_med <= 0.05);
* the estimated alpha-quantile c of the boundary p_med: the k-th smallest of the R boundary
  values with k = floor(alpha R), so that the empirical boundary size at c is k / R <= alpha;
* the size-adjusted power: share of replications whose alternative p_med is at most c;
* the paired comparison: replications in which the alternative p_med is below the boundary
  p_med of the same replication (same R_past*, same test seeds).

Inputs (written by experiments/e3_sp500.py and experiments/e5_robustness.py):
``results/e3/e3_power_raw.csv`` (D1, main split), ``results/e3/e3_realvol_raw.csv`` (D2, main
split), ``results/e5/e5_split_power_raw.csv`` (D1 and D2, alternative split, config
``default``). Output: ``paper/tables/manual_theory_calibration.tex`` (bare tabular).

Usage (from the repository root)::

    uv run python paper/scripts/theory_calibration.py
"""
from __future__ import annotations

import math
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[2]
RES = ROOT / "results"
OUT = ROOT / "paper" / "tables" / "manual_theory_calibration.tex"
ALPHA = 0.05


def rule_pvalues(df: pd.DataFrame) -> pd.DataFrame:
    """p_med per replication (rows) and case (columns: alternative, boundary)."""
    n = df.groupby(["rep", "case"])["pvalue"].size()
    if n.nunique() != 1:
        raise ValueError(f"unequal number of seeds per replication: {sorted(n.unique())}")
    if set(df["pvalue_type"].unique()) != {"hac"}:
        raise ValueError("expected Driscoll-Kraay (hac) p-values only")
    g = df.groupby(["rep", "case"])["pvalue"].agg(lambda p: min(1.0, 2.0 * float(np.median(p))))
    return g.unstack("case")[["alternative", "boundary"]]


def sources() -> dict[tuple[str, str], pd.DataFrame]:
    alt = pd.read_csv(RES / "e5" / "e5_split_power_raw.csv")
    alt = alt[(alt["data_split"] == "alt") & (alt["config"] == "default")]
    return {
        ("Main", "D1"): pd.read_csv(RES / "e3" / "e3_power_raw.csv"),
        ("Main", "D2"): pd.read_csv(RES / "e3" / "e3_realvol_raw.csv"),
        ("Alternative", "D1"): alt[alt["design"] == "D1"],
        ("Alternative", "D2"): alt[alt["design"] == "D2"],
    }


def sci(v: float) -> str:
    """Two significant digits; scientific notation below 0.001."""
    if v >= 1e-3:
        return f"{v:.3f}"
    m, e = f"{v:.1e}".split("e")
    return rf"${m}\times10^{{{int(e)}}}$"


def main() -> None:
    rows = []
    for (split, design), df in sources().items():
        g = rule_pvalues(df)
        R = len(g)
        S = int(df.groupby(["rep", "case"])["pvalue"].size().iloc[0])
        bd = np.sort(g["boundary"].to_numpy())
        k = int(math.floor(ALPHA * R))
        if k < 1:
            raise ValueError(f"R = {R} too small for alpha = {ALPHA}")
        c = float(bd[k - 1])
        rows.append({
            "split": split, "design": design, "R": R, "S": S,
            "size_nom": float(np.mean(g["boundary"] <= ALPHA)),
            "power_nom": float(np.mean(g["alternative"] <= ALPHA)),
            "k": k, "c": c, "size_c": k / R,
            "power_adj": float(np.mean(g["alternative"] <= c)),
            "paired_below": int(np.sum(g["alternative"] < g["boundary"])),
        })
        print(rows[-1])

    lines = [
        "% generated by paper/scripts/theory_calibration.py from results/e3/e3_power_raw.csv,",
        "% results/e3/e3_realvol_raw.csv and results/e5/e5_split_power_raw.csv",
        r"\begin{tabular}{llrrrrrrr}",
        r"\toprule",
        r" & & & \multicolumn{2}{c}{Nominal $\alpha=0.05$}"
        r" & \multicolumn{3}{c}{Size-adjusted} & \\",
        r"\cmidrule(lr){4-5}\cmidrule(lr){6-8}",
        r"Split & Design & $R\times S$ & Boundary size & Power & $\hat c_\alpha$"
        r" & Boundary size at $\hat c_\alpha$ & Power at $\hat c_\alpha$"
        r" & $p^{\mathrm{alt}}_r<p^{\mathrm{bd}}_r$ \\",
        r"\midrule",
    ]
    for r in rows:
        lines.append(
            f"{r['split']} & {r['design']} & {r['R']} $\\times$ {r['S']} & "
            f"{r['size_nom']:.2f} & {r['power_nom']:.2f} & {sci(r['c'])} & "
            f"{r['size_c']:.2f} & {r['power_adj']:.2f} & {r['paired_below']}/{r['R']} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}", ""]
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
