"""Narrow appendix tables for Appendix G (Robustness: details) from the E5 / E5-arch / E3 CSVs.

The generated tables ``e5_split.tex`` and ``e5_arch_real.tex`` are too wide for the text width
(shrunk below 7pt). This script writes narrower bare booktabs tabulars with the same numbers:

``paper/tables/manual_e5_split_battery.tex``
    alternative split, every test of the E3 battery per generator: ``min(1, 2 x median p)`` over
    the five synthetic seeds for the W-critic, LR-critic, C2ST (Driscoll-Kraay), MMD, Sig-MMD
    (wild bootstrap), KS (asymptotic i.i.d., invalid), the anchored and the two-critic relative
    tests, and the verdict. The rule power / boundary size rows are in ``manual_e5_split.tex``
    (``paper/scripts/e5_tables.py``). Source: ``results/e5/e5_split.csv``.
``paper/tables/manual_e5_arch_real.tex``
    E3 protocol with the default MLP critic and the time-pooled CNN critic: absolute W-critic and
    anchored ``min(1, 2 x median p)`` and verdicts per generator; rule power (Wilson 95%) and
    boundary size (Clopper-Pearson 95%) under D1 and D2 for the MLP over E3's 100 replications,
    the MLP over the first 20 replications and the pooled critic over the same 20 replications.
    The rule is ``min(1, 2 x median p over the five seeds) <= 0.05``, recomputed from the
    replication rows. Sources: ``results/e5arch/e5arch_real_summary.csv``,
    ``results/e5arch/e5_gridpower_raw.csv`` (D1, pooled), ``results/e5arch/e5_gridrealvol_raw.csv``
    (D2, pooled), ``results/e3/e3_power_raw.csv`` (D1, MLP), ``results/e3/e3_realvol_raw.csv``
    (D2, MLP).

    uv run python paper/scripts/e5_app_tables.py
"""
from __future__ import annotations

import sys
from pathlib import Path

import numpy as np
import pandas as pd
from statsmodels.stats.proportion import proportion_confint

ROOT = Path(__file__).resolve().parents[2]
E5 = ROOT / "results" / "e5"
E5A = ROOT / "results" / "e5arch"
E3 = ROOT / "results" / "e3"
TABLES = ROOT / "paper" / "tables"
ALPHA = 0.05
MODELS = ("GBM", "Merton", "GARCHt", "Heston", "Bootstrap")
LABELS = {"GBM": "GBM", "Merton": "Merton", "GARCHt": r"GARCH-$t$", "Heston": "Heston",
          "Bootstrap": "Stat.\\ bootstrap"}
VMACRO = {"BAD": r"\BAD", "INCONCLUSIVE": r"\INCONCL", "GOOD": r"\GOOD", "INVALID": r"\INVALID"}
DAG, DDAG = r"$^\dagger$", r"$^\ddagger$"


def fmt_p(p: float) -> str:
    """As in experiments/e5_robustness.py: '<0.001' below 0.001, else 3 decimals."""
    if not np.isfinite(p):
        return "--"
    return "$<$0.001" if p < 0.001 else f"{p:.3f}"


def true(x) -> bool:
    return False if pd.isna(x) else str(x).strip().lower() in ("true", "1", "1.0")


def verdict(v) -> str:
    return "n/a" if pd.isna(v) else VMACRO[str(v)]


def split_battery() -> list[str]:
    a = pd.read_csv(E5 / "e5_split.csv")
    tests = [("critic", r"\WC{}"), ("lrcritic", r"\LRC{}"), ("c2st", "C2ST"), ("mmd", "MMD"),
             ("sigmmd", r"\SigMMD{}"), ("ks", r"KS$^\ast$"),
             ("relative_anchored", "Anchored"), ("relative_two_critic", "Two-critic" + DAG)]
    lines = [
        r"\begin{tabular}{l" + "r" * len(tests) + "l}",
        r"\toprule",
        r" & \multicolumn{6}{c}{Absolute tests} & \multicolumn{2}{c}{Relative tests} & \\",
        r"\cmidrule(lr){2-7} \cmidrule(lr){8-9}",
        "Generator & " + " & ".join(t[1] for t in tests) + r" & Verdict \\",
        r"\midrule",
    ]
    for m in MODELS:
        g = a[a["model"] == m].set_index("test")
        cells = [LABELS[m]]
        rel_ok = true(g.loc["relative_anchored", "valid"])
        for t, _ in tests:
            p = float(g.loc[t, "p_comb"])
            c = fmt_p(p)
            if t.startswith("relative") and not rel_ok:
                c += DDAG
            elif t in ("critic", "lrcritic", "c2st", "mmd", "sigmmd", "relative_anchored") \
                    and true(g.loc[t, "valid"]) and p <= ALPHA:
                c = rf"\textbf{{{c}}}"
            cells.append(c)
        cells.append(verdict(g.loc["relative_anchored", "verdict_alt"]))
        lines.append(" & ".join(cells) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}",
              "% generated by paper/scripts/e5_app_tables.py from results/e5/e5_split.csv"]
    return lines


def rule_counts(df: pd.DataFrame, reps: int | None = None) -> dict[str, tuple[int, int]]:
    """Per case: (number of replications with min(1, 2 median p) <= alpha, replications)."""
    if reps is not None:
        df = df[df["rep"] < reps]
    pm = df.groupby(["rep", "case"])["pvalue"].apply(
        lambda p: min(1.0, 2.0 * float(np.median(p)))).unstack()
    return {c: (int((pm[c] <= ALPHA).sum()), int(pm[c].notna().sum())) for c in pm.columns}


def fmt_ci(k: int, n: int, method: str) -> str:
    lo, hi = proportion_confint(k, n, alpha=0.05, method=method)
    return f"{k / n:.2f} [{lo:.2f}, {hi:.2f}]"


def arch_real() -> list[str]:
    s = pd.read_csv(E5A / "e5arch_real_summary.csv").set_index("model")
    lines = [
        r"\begin{tabular}{lllllll}",
        r"\toprule",
        r" & \multicolumn{2}{c}{Absolute \WC{} (seeds rej.)} & \multicolumn{2}{c}{Anchored}"
        r" & \multicolumn{2}{c}{Verdict} \\",
        r"\cmidrule(lr){2-3} \cmidrule(lr){4-5} \cmidrule(lr){6-7}",
        r"Generator & MLP & pooled & MLP & pooled & MLP & pooled \\",
        r"\midrule",
    ]
    for m in MODELS:
        r = s.loc[m]
        lines.append(" & ".join([
            LABELS[m],
            f"{fmt_p(float(r['abs_mlp']))} ({r['abs_rej_mlp']})",
            f"{fmt_p(float(r['abs_pooled']))} ({r['abs_rej_pooled']})",
            fmt_p(float(r["rel_mlp"])), fmt_p(float(r["rel_pooled"])),
            verdict(r["verdict_mlp"]), verdict(r["verdict_pooled"])]) + r" \\")
    pooled = {"D1": pd.read_csv(E5A / "e5_gridpower_raw.csv"),
              "D2": pd.read_csv(E5A / "e5_gridrealvol_raw.csv")}
    mlp = {"D1": pd.read_csv(E3 / "e3_power_raw.csv"),
           "D2": pd.read_csv(E3 / "e3_realvol_raw.csv")}
    lines += [
        r"\midrule",
        r"Rule & \multicolumn{2}{l}{MLP, all replications} & \multicolumn{2}{l}{MLP, paired"
        r" replications} & \multicolumn{2}{l}{pooled, paired replications} \\",
        r"\midrule",
    ]
    for case, lab, method in (("alternative", "power", "wilson"),
                              ("boundary", "boundary size", "beta")):
        for d in ("D1", "D2"):
            n_pooled = int(pooled[d]["rep"].nunique())
            cp = rule_counts(pooled[d])[case]
            cm = rule_counts(mlp[d])[case]
            cmp_ = rule_counts(mlp[d], reps=n_pooled)[case]
            lines.append(" & ".join([
                f"{d} {lab}",
                rf"\multicolumn{{2}}{{l}}{{{fmt_ci(*cm, method)} ({cm[1]})}}",
                rf"\multicolumn{{2}}{{l}}{{{fmt_ci(*cmp_, method)} ({cmp_[1]})}}",
                rf"\multicolumn{{2}}{{l}}{{{fmt_ci(*cp, method)} ({cp[1]})}}"]) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}",
              "% generated by paper/scripts/e5_app_tables.py from results/e5arch/"
              "e5arch_real_summary.csv, e5_gridpower_raw.csv, e5_gridrealvol_raw.csv, "
              "results/e3/e3_power_raw.csv, e3_realvol_raw.csv"]
    return lines


def main() -> int:
    for name, fn in (("manual_e5_split_battery", split_battery),
                     ("manual_e5_arch_real", arch_real)):
        out = TABLES / f"{name}.tex"
        out.write_text("\n".join(fn()) + "\n")
        print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
