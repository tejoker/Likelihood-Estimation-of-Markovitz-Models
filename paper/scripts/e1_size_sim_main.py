"""Condensed main-text version of the E1(a) placebo size table (Section 5, label tab:e1-size-sim).

Reads ``results/e1/e1_size_sim.csv`` (written by ``experiments/e1_placebo.py --part sim``) and
writes ``paper/tables/manual_e1_size_sim_main.tex``: rejection rates at nominal 5% with Wilson 95%
intervals, same rounding as the generated ``e1_size_sim.tex``, for a subset of the p-value types
and both placebo cells side by side (``joint``: the synthetic panel is an independent draw of the
whole factor panel; ``indep``: tickers drawn independently with the same marginal laws). The full
table (all p-value types, alpha in {0.01, 0.05, 0.10}) is ``e1_size_sim.tex`` in Appendix C.

Usage (from the repository root)::

    uv run python paper/scripts/e1_size_sim_main.py
"""
from __future__ import annotations

import math
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "results" / "e1" / "e1_size_sim.csv"
OUT = ROOT / "paper" / "tables" / "manual_e1_size_sim_main.tex"

TEST_TEX = {"critic": r"\WC{}", "lrcritic": r"\LRC{}", "c2st": "C2ST", "mmd": "MMD",
            "sigmmd": r"\SigMMD{}", "ks": "KS", "relative_anchored": "Anchored relative",
            "relative_two_critic": "Two-critic relative"}
# (test, ptype, split label, p-value label, protocol p-value?)
ROWS = [
    ("critic", "hac", "time blocks", "Driscoll--Kraay", True),
    ("critic", "hac_fixedb", "time blocks", r"Driscoll--Kraay, fixed-$b$ (cons.)", False),
    ("critic", "hac_fixedb_eq", "time blocks", r"Driscoll--Kraay, fixed-$b$ (eq.\ var.)", False),
    ("critic", "timeblock_permutation", "time blocks", "permutation", False),
    ("critic", "ticker_hac", "tickers", "Driscoll--Kraay", False),
    ("critic", "ticker_permutation", "tickers", "permutation", False),
    ("lrcritic", "hac", "time blocks", "Driscoll--Kraay", True),
    ("lrcritic", "timeblock_permutation", "time blocks", "permutation", False),
    ("lrcritic", "ticker_permutation", "tickers", "permutation", False),
    ("c2st", "hac", "time blocks", "Driscoll--Kraay", True),
    ("c2st", "ticker_permutation", "tickers", "permutation", False),
    ("mmd", "wild", "none", "wild bootstrap", True),
    ("mmd", "permutation", "none", "permutation", False),
    ("sigmmd", "wild", "none", "wild bootstrap", True),
    ("sigmmd", "permutation", "none", "permutation", False),
    ("ks", "asymptotic", "none", r"asymptotic (\iid{}; invalid)", False),
    ("relative_anchored", "hac", "time blocks", "Driscoll--Kraay", True),
    ("relative_anchored", "hac_fixedb_eq", "time blocks",
     r"Driscoll--Kraay, fixed-$b$ (eq.\ var.)", False),
    ("relative_anchored", "timeblock_permutation", "time blocks", "permutation", False),
    ("relative_two_critic", "hac", "time blocks", "Driscoll--Kraay", True),
    ("relative_two_critic", "paired_bootstrap", "time blocks", "paired bootstrap", False),
]
CELLS = ("joint", "indep")


def num(v: float, d: int = 3) -> str:
    return "--" if v is None or not math.isfinite(float(v)) else f"{float(v):.{d}f}"


def main() -> None:
    df = pd.read_csv(SRC)
    if not (df["n_valid"] == 200).all() or (df["n_nan"] != 0).any():
        raise SystemExit("unexpected replication counts in e1_size_sim.csv")
    idx = df.set_index(["synth", "test", "ptype"])
    lines = [
        r"\begin{tabular}{lllcc}",
        r"\toprule",
        r" & & & \multicolumn{2}{c}{Rejection rate at $\alpha=0.05$} \\",
        r"\cmidrule(lr){4-5}",
        r"Test & Split & $p$-value & $G^*$ joint & $G^*$ indep. \\",
        r"\midrule",
    ]
    prev = None
    for test, ptype, split, plab, star in ROWS:
        cells = []
        for c in CELLS:
            r = idx.loc[(c, test, ptype)]
            cells.append(f"{num(r['rej_0.05'])} [{num(r['lo_0.05'])}, {num(r['hi_0.05'])}]")
        name = TEST_TEX[test] if test != prev else ""
        if prev is not None and test != prev:
            lines.append(r"\addlinespace[2pt]")
        mark = r"$^{\star}$" if star else ""
        lines.append(f"{name} & {split} & {plab}{mark} & " + " & ".join(cells) + r" \\")
        prev = test
    lines += [r"\bottomrule", r"\end{tabular}"]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("% generated by paper/scripts/e1_size_sim_main.py from results/e1/e1_size_sim.csv\n"
                   + "\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
