"""Statistic versus standard error in the E1(a) placebo (main text, label tab:e1-sim-se).

Reads ``results/e1/e1_sim_raw.csv`` (written by ``experiments/e1_placebo.py --part sim``) and
writes ``paper/tables/manual_e1_sim_se.tex``. Rows: the learned absolute tests (\\WC{}, \\LRC{})
and the two relative tests under the time-block split with the Driscoll--Kraay p-value, in the
cells ``joint`` and ``indep``. C2ST is left out because its statistic is an accuracy and its
studentised statistic is not the ratio of the stored statistic and standard error.

Columns, over the 200 placebo replications of a cell:

* mean and standard deviation of the raw statistic T (``statistic``);
* median Driscoll--Kraay standard error (``se_hac``; z_hac = T / se_hac for these tests, which
  the script checks);
* ratio of the Monte Carlo standard deviation of T to the root mean square of the standard error
  (about 1 if the average estimated variance matches the variance of T over replications; the
  ratio to the median standard error, which the skewness of the standard error inflates, is
  printed by the script but not tabulated);
* Spearman rank correlation of T and its standard error across replications;
* rejection rate at nominal 5% (z_hac > 1.645) in the replications whose standard error is at or
  below the cell median, and in those above it (the two halves average to the size of
  tab:e1-size-sim).

Usage (from the repository root)::

    uv run python paper/scripts/e1_sim_se_diag.py
"""
from __future__ import annotations

import math
from pathlib import Path

import numpy as np
import pandas as pd
from scipy import stats

ROOT = Path(__file__).resolve().parents[2]
RAW = ROOT / "results" / "e1" / "e1_sim_raw.csv"
OUT = ROOT / "paper" / "tables" / "manual_e1_sim_se.tex"

TEST_TEX = {"critic": r"\WC{}", "lrcritic": r"\LRC{}",
            "relative_anchored": "Anchored relative", "relative_two_critic": "Two-critic relative"}
Z05 = 1.6448536269514722
HEADER = "% generated by paper/scripts/e1_sim_se_diag.py from results/e1/e1_sim_raw.csv\n"


def num(v: float, d: int = 3) -> str:
    if v is None or not math.isfinite(float(v)):
        return "--"
    v = float(v)
    if abs(v) < 0.5 * 10.0 ** (-d):
        v = 0.0  # print 0.000, not -0.000
    return f"{v:.{d}f}"


def main() -> None:
    d = pd.read_csv(RAW, low_memory=False)
    sel = d[((d["kind"] == "absolute") & (d["split"] == "time_block")
             & (d["pvalue_type"] == "hac"))
            | ((d["kind"] == "relative") & (d["pvalue_type"] == "hac"))].copy()
    for c in ("statistic", "se_hac", "z_hac"):
        sel[c] = pd.to_numeric(sel[c], errors="coerce")
    lines = [r"\begin{tabular}{llrrrrrrr}", r"\toprule",
             r" & & & & & & & \multicolumn{2}{c}{Size at 5\%, s.e.} \\",
             r"\cmidrule(lr){8-9}",
             r"$G^*$ & Test & mean $T$ & sd $T$ & median s.e. & sd $T$/rms s.e."
             r" & Spearman$(T,\text{s.e.})$ & $\le$ median & $>$ median \\",
             r"\midrule"]
    for cell, ctex in (("joint", "joint"), ("indep", "indep.")):
        first = True
        for test, ttex in TEST_TEX.items():
            g = sel[(sel["synth"] == cell) & (sel["test"] == test)].dropna(
                subset=["statistic", "se_hac", "z_hac"])
            if g.empty:
                continue
            t, se, z = (g[c].to_numpy(float) for c in ("statistic", "se_hac", "z_hac"))
            if not np.allclose(z, t / se, rtol=1e-6, atol=1e-9):
                raise ValueError(f"z_hac != statistic / se_hac for {cell}/{test}")
            low = se <= np.median(se)
            print(f"{cell:6s} {test:20s} sd T / median se = {t.std(ddof=1) / np.median(se):.2f}")
            row = [ctex if first else "", ttex, num(t.mean()), num(t.std(ddof=1)),
                   num(np.median(se)), num(t.std(ddof=1) / np.sqrt(np.mean(se ** 2)), 2),
                   num(stats.spearmanr(t, se)[0], 2),
                   num(np.mean(z[low] > Z05)), num(np.mean(z[~low] > Z05))]
            lines.append(" & ".join(row) + r" \\")
            first = False
        if cell == "joint":
            lines.append(r"\addlinespace[2pt]")
    lines += [r"\bottomrule", r"\end{tabular}"]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(HEADER + "\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
