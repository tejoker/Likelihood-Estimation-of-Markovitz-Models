"""Condensed main-text tables for Section 9 (Robustness) from the E5 and E3 CSVs.

Writes two bare booktabs tabulars (the full generated tables ``e5_sensitivity.tex`` and
``e5_split.tex`` are too wide for the main text and go to Appendix G):

``paper/tables/manual_e5_sensitivity.tex``
    per grid configuration: the anchored relative p-value ``min(1, 2 x median p)`` over the five
    synthetic seeds with the verdict (B / I) for each generator (dagger: the relative decision at
    5% differs from the default; double dagger: relative test invalid for the stationary
    bootstrap) and the number of generators the absolute W-critic test rejects at 5%.
    Source: ``results/e5/e5_sensitivity.csv``.
``paper/tables/manual_e5_split.tex``
    alternative versus main split: absolute W-critic and anchored p-values and verdicts per
    generator, and the rule's power (Wilson 95%) and boundary size (Clopper-Pearson 95%) under
    D1 and D2. Sources: ``results/e5/e5_split.csv``, ``results/e5/e5_split_power.csv``,
    ``results/e3/e3_power_summary.csv`` (D1, main split), ``results/e3/e3_realvol_summary.csv``
    (D2, main split).

    uv run python paper/scripts/e5_tables.py
"""
from __future__ import annotations

import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[2]
E5 = ROOT / "results" / "e5"
E3 = ROOT / "results" / "e3"
TABLES = ROOT / "paper" / "tables"
ALPHA = 0.05
MODELS = ("GBM", "Merton", "GARCHt", "Heston", "Bootstrap")
LABELS = {"GBM": "GBM", "Merton": "Merton", "GARCHt": r"GARCH-$t$", "Heston": "Heston",
          "Bootstrap": "Stat.\\ bootstrap"}
VSHORT = {"BAD": "B", "INCONCLUSIVE": "I", "GOOD": "G"}
VMACRO = {"BAD": r"\BAD", "INCONCLUSIVE": r"\INCONCL", "GOOD": r"\GOOD"}
DAG, DDAG = r"$^\dagger$", r"$^\ddagger$"


def fmt_p(p: float) -> str:
    """As in experiments/e5_robustness.py: '<0.001' below 0.001, else 3 decimals."""
    if not np.isfinite(p):
        return "--"
    return "$<$0.001" if p < 0.001 else f"{p:.3f}"


def fmt_rate(r: float, lo: float, hi: float) -> str:
    return f"{r:.2f} [{lo:.2f}, {hi:.2f}]"


def true(x) -> bool:
    return False if pd.isna(x) else str(x).strip().lower() in ("true", "1", "1.0")


def sensitivity() -> list[str]:
    s = pd.read_csv(E5 / "e5_sensitivity.csv")
    lines = [
        r"\begin{tabular}{llrrrrrr}",
        r"\toprule",
        r" & & \multicolumn{5}{c}{Anchored relative test: $p_{\mathrm{med}}$ and verdict}"
        r" & Absolute \\",
        r"\cmidrule(lr){3-7}",
        r"Factor & Setting & " + " & ".join(LABELS[m] for m in MODELS)
        + r" & rejections \\",
        r"\midrule",
    ]
    prev = None
    for cfg, g in s.groupby("config", sort=False):
        g = g.set_index("model")
        factor = str(g["factor"].iloc[0])
        shown = factor.replace(r"GP weight $\lambda$", r"GP weight $\lgp$")
        cells = [shown if factor != prev else "", str(g["setting"].iloc[0])]
        prev = factor
        for m in MODELS:
            r = g.loc[m]
            if not true(r["rel_valid"]):
                cells.append(fmt_p(float(r["p_rel_comb"])) + DDAG)
                continue
            c = f"{fmt_p(float(r['p_rel_comb']))} {VSHORT[str(r['verdict'])]}"
            if cfg != "default" and true(r["rel_decision_changed"]):
                c += DAG
            cells.append(c)
        k = int((g["p_abs_comb"].astype(float) <= ALPHA).sum())
        cells.append(f"{k}/{len(g)}")
        lines.append(" & ".join(cells) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}",
              "% generated by paper/scripts/e5_tables.py from results/e5/e5_sensitivity.csv"]
    return lines


def split() -> list[str]:
    a = pd.read_csv(E5 / "e5_split.csv")
    pw = pd.read_csv(E5 / "e5_split_power.csv")
    main = pd.concat([pd.read_csv(E3 / "e3_power_summary.csv"),
                      pd.read_csv(E3 / "e3_realvol_summary.csv")], ignore_index=True)
    lines = [
        r"\begin{tabular}{lrrlrl}",
        r"\toprule",
        r" & \multicolumn{3}{c}{Alternative split} & \multicolumn{2}{c}{Main split (E3)} \\",
        r"\cmidrule(lr){2-4} \cmidrule(lr){5-6}",
        r"Generator & Absolute & Anchored & Verdict & Anchored & Verdict \\",
        r"\midrule",
    ]
    for m in MODELS:
        g = a[a["model"] == m].set_index("test")
        inv = DDAG if not true(g.loc["relative_anchored", "valid"]) else ""
        pab = float(g.loc["critic", "p_comb"])
        ab = fmt_p(pab)
        if pab <= ALPHA:
            ab = rf"\textbf{{{ab}}}"
        v_alt = g.loc["relative_anchored", "verdict_alt"]
        v_main = g.loc["relative_anchored", "verdict_main"]
        v_alt = "n/a" if pd.isna(v_alt) else VMACRO[str(v_alt)]
        v_main = "n/a" if pd.isna(v_main) else VMACRO[str(v_main)]
        lines.append(" & ".join([
            LABELS[m], ab, fmt_p(float(g.loc["relative_anchored", "p_comb"])) + inv, v_alt,
            fmt_p(float(g.loc["relative_anchored", "p_rel_main"])) + inv, v_main]) + r" \\")
    lines.append(r"\midrule")

    def row(df: pd.DataFrame, d: str, case: str) -> str:
        r = df[(df["design"] == d) & (df["case"] == case)].iloc[0]
        if case == "alternative":  # power: Wilson interval
            return fmt_rate(r["rate_rule"], r["rule_ci_lo"], r["rule_ci_hi"])
        return fmt_rate(r["rate_rule"], r["rule_cp_lo"], r["rule_cp_hi"])  # Clopper-Pearson

    for case, lab in (("alternative", r"Rule power {d} (vol.\ $\times1.2$)"),
                      ("boundary", r"Rule boundary size {d}")):
        for d in ("D1", "D2"):
            na = int(pw[(pw["design"] == d) & (pw["case"] == case)]["n_reps"].iloc[0])
            nm = int(main[(main["design"] == d) & (main["case"] == case)]["n_reps"].iloc[0])
            lines.append(" & ".join([lab.format(d=d), "",
                                     rf"\multicolumn{{2}}{{l}}{{{row(pw, d, case)} ({na})}}",
                                     rf"\multicolumn{{2}}{{l}}{{{row(main, d, case)} ({nm})}}"])
                         + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}",
              "% generated by paper/scripts/e5_tables.py from results/e5/e5_split.csv, "
              "e5_split_power.csv, results/e3/e3_power_summary.csv, e3_realvol_summary.csv"]
    return lines


def main() -> int:
    for name, fn in (("manual_e5_sensitivity", sensitivity), ("manual_e5_split", split)):
        out = TABLES / f"{name}.tex"
        out.write_text("\n".join(fn()) + "\n")
        print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
