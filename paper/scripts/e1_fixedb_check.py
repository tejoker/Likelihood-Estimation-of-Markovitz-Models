"""Monte Carlo check of the conservative fixed-b reference of E1(a) (Appendix C, app:sim-e1).

The conservative fixed-b p-value of ``experiments/e1_placebo.py`` (ptype ``hac_fixedb``) refers
the two-sample Driscoll-Kraay statistic ``z = (mean x - mean y) / sqrt(V_x + V_y)`` to the
finite-sample fixed-b reference of a single series with ``U = min(U_x, U_y)`` evaluation dates and
Bartlett lag ``H = max(H_x, H_y)``. This script checks, for every combination
``(U_x, H_x, U_y, H_y)`` that occurs in the fixed-b rows of ``results/e1/e1_sim_raw.csv``
(absolute tests with the time-block split and the anchored relative test, both cells), whether
that reference is conservative for the two-sample statistic whatever the share ``lam`` of the
first sample in the variance of the mean difference.

For each combination, ``M`` independent pairs of contiguous i.i.d. N(0, 1) series of lengths
``U_x`` and ``U_y`` are drawn; with weights ``a^2 = lam U_x`` and ``b^2 = (1 - lam) U_y`` the
two-sample statistic is ``(a xbar - b ybar) / sqrt(a^2 V_x + b^2 V_y)`` (Bartlett variances of
the means with lags ``H_x`` and ``H_y``, as in the pipeline reference), for ``lam`` on a grid of
21 values in [0, 1] (``lam = 0, 1``: a single series). Each draw gets the pipeline's conservative
p-value (same reference draws, same seed and same Monte Carlo p-value formula as
``experiments/e1_placebo.py::fixedb_pvalue``, copied here to avoid importing the experiment
module) and the rejection rate at alpha in {0.01, 0.05, 0.10} is recorded. Like the pipeline
references, the check treats the evaluation dates as contiguous.

Writes ``paper/tables/manual_e1_fixedb_check.tex`` and prints a summary.

Usage (from the repository root)::

    uv run python paper/scripts/e1_fixedb_check.py
"""
from __future__ import annotations

import functools
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[2]
RAW = ROOT / "results" / "e1" / "e1_sim_raw.csv"
OUT = ROOT / "paper" / "tables" / "manual_e1_fixedb_check.tex"
HEADER = "% generated by paper/scripts/e1_fixedb_check.py from results/e1/e1_sim_raw.csv\n"

# Pipeline reference (copied from experiments/e1_placebo.py)
FIXEDB_DRAWS = 40_000
FIXEDB_SEED = 20251115
# This check
CHECK_DRAWS = 200_000
CHECK_SEED = 20261116
LAMS = np.linspace(0.0, 1.0, 21)
ALPHAS = (0.01, 0.05, 0.10)
GROUPS = {"absolute": "Absolute (\\WC{}, \\LRC{}, C2ST)", "anchored": "Anchored relative"}


def _bartlett_var_of_mean(E: np.ndarray, H: int) -> np.ndarray:
    """Bartlett variance of the mean of each demeaned row of ``E`` (copy of the pipeline's)."""
    T = E.shape[1]
    lrv = np.einsum("ij,ij->i", E, E)
    for h in range(1, min(int(H), T - 1) + 1):
        lrv += 2.0 * (1.0 - h / (H + 1.0)) * np.einsum("ij,ij->i", E[:, h:], E[:, :-h])
    return np.maximum(lrv, 0.0) / T**2


@functools.lru_cache(maxsize=256)
def fixedb_reference(T_x: int, H_x: int, T_y: int = 0, H_y: int = 0) -> np.ndarray:
    """Sorted symmetrised reference draws (copy of ``experiments/e1_placebo.py``)."""
    rng = np.random.default_rng([FIXEDB_SEED, int(T_x), int(H_x), int(T_y), int(H_y)])
    X = rng.standard_normal((FIXEDB_DRAWS, int(T_x)))
    mx = X.mean(axis=1)
    v = _bartlett_var_of_mean(X - mx[:, None], H_x)
    num = mx
    if T_y:
        Y = rng.standard_normal((FIXEDB_DRAWS, int(T_y)))
        my = Y.mean(axis=1)
        v = v + _bartlett_var_of_mean(Y - my[:, None], H_y)
        num = mx - my
    with np.errstate(divide="ignore", invalid="ignore"):
        t = num / np.sqrt(v)
    t = t[np.isfinite(t)]
    return np.sort(np.concatenate([t, -t]))


def _upper_tail(ref: np.ndarray, z: np.ndarray) -> np.ndarray:
    """Monte Carlo upper-tail p-value ``(1 + #{ref >= z}) / (1 + len(ref))``."""
    return (1.0 + ref.size - np.searchsorted(ref, z, side="left")) / (1.0 + ref.size)


def combinations() -> pd.DataFrame:
    d = pd.read_csv(RAW, low_memory=False)
    sel = d[((d["kind"] == "absolute") & (d["split"] == "time_block")
             & (d["pvalue_type"] == "hac"))
            | ((d["kind"] == "relative") & (d["test"] == "relative_anchored")
               & (d["pvalue_type"] == "hac"))].copy()
    cols = ["T_eval_x", "H_x", "T_eval_y", "H_y"]
    sel = sel.dropna(subset=cols + ["z_hac"])
    for c in cols:
        sel[c] = np.round(pd.to_numeric(sel[c])).astype(int)
    sel["group"] = np.where(sel["kind"] == "absolute", "absolute", "anchored")
    return (sel.groupby(["group"] + cols).size().rename("n_calls").reset_index())


def check_one(Ux: int, Hx: int, Uy: int, Hy: int, rng: np.random.Generator) -> np.ndarray:
    """Rejection rates, shape (len(LAMS), len(ALPHAS)), at the conservative reference."""
    ref = fixedb_reference(min(Ux, Uy), max(Hx, Hy))
    X = rng.standard_normal((CHECK_DRAWS, Ux))
    Y = rng.standard_normal((CHECK_DRAWS, Uy))
    mx, my = X.mean(axis=1), Y.mean(axis=1)
    vx = _bartlett_var_of_mean(X - mx[:, None], Hx)
    vy = _bartlett_var_of_mean(Y - my[:, None], Hy)
    out = np.empty((LAMS.size, len(ALPHAS)))
    for i, lam in enumerate(LAMS):
        a2, b2 = lam * Ux, (1.0 - lam) * Uy
        with np.errstate(divide="ignore", invalid="ignore"):
            z = (np.sqrt(a2) * mx - np.sqrt(b2) * my) / np.sqrt(a2 * vx + b2 * vy)
        z = z[np.isfinite(z)]
        p = np.concatenate([_upper_tail(ref, z), _upper_tail(ref, -z)])  # symmetric law
        out[i] = [(p <= a).mean() for a in ALPHAS]
    return out


def main() -> None:
    combos = combinations()
    rng = np.random.default_rng(CHECK_SEED)
    rows = []
    for r in combos.itertuples(index=False):
        rates = check_one(r.T_eval_x, r.H_x, r.T_eval_y, r.H_y, rng)
        for i, lam in enumerate(LAMS):
            rows.append({"group": r.group, "Ux": r.T_eval_x, "Hx": r.H_x, "Uy": r.T_eval_y,
                         "Hy": r.H_y, "n_calls": r.n_calls, "lam": lam,
                         **{f"rate_{a:g}": rates[i, j] for j, a in enumerate(ALPHAS)}})
    res = pd.DataFrame(rows)
    interior = res[(res["lam"] > 0) & (res["lam"] < 1)]
    lines = [r"\begin{tabular}{lrr" + "c" * len(ALPHAS) + "}", r"\toprule",
             r"Test & Combinations & Calls & "
             + " & ".join(f"$\\alpha={a:g}$" for a in ALPHAS) + r" \\", r"\midrule"]
    for g, label in GROUPS.items():
        sub = res[res["group"] == g]
        sub_in = interior[interior["group"] == g]
        ncomb = len(combos[combos["group"] == g])
        ncall = int(combos.loc[combos["group"] == g, "n_calls"].sum())
        cells = []
        for a in ALPHAS:
            c = f"rate_{a:g}"
            cells.append(f"{sub_in[c].max():.4f} ({sub[c].max():.4f})")
        lines.append(f"{label} & {ncomb} & {ncall} & " + " & ".join(cells) + r" \\")
        print(g, "combinations", ncomb, "calls", ncall)
        for a in ALPHAS:
            c = f"rate_{a:g}"
            k = sub[c].idxmax()
            print(f"  alpha={a:g}: max over lam in (0,1) {sub_in[c].max():.4f}, over [0,1] "
                  f"{sub[c].max():.4f} at {res.loc[k, ['Ux', 'Hx', 'Uy', 'Hy', 'lam']].tolist()}")
    lines += [r"\bottomrule", r"\end{tabular}"]
    OUT.write_text(HEADER + "\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT}")
    se = {a: np.sqrt(a * (1 - a) / CHECK_DRAWS) for a in ALPHAS}
    print("Monte Carlo s.e. of one rate (200,000 draws, before symmetrisation):",
          {a: round(s, 5) for a, s in se.items()})


if __name__ == "__main__":
    main()
