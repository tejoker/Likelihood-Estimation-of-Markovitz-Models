"""Statistic and standard error of the absolute learned tests in the E1(a) placebo (both cells).

Supports the discussion of the oversize of the time-block / Driscoll-Kraay protocol when the
synthetic tickers are independent (Section 4.7: cor:block-bias, rem:small-T; Section 5.6). For the
absolute W-critic and LR-critic tests under the placebo null (time-block split, Driscoll-Kraay
p-value, 200 replications per cell) it reports, per cell (``joint``: G* an independent draw of the
whole factor panel; ``indep``: independent tickers):

* the mean of the statistic T over the replications with its Monte Carlo standard error
  (sd / sqrt(N)), the standard deviation of T and the share of replications with T > 0;
* the median Driscoll-Kraay standard error ``se_hac`` of T and the Pearson correlation of T with
  ``se_hac`` over the replications;
* the mean of z_hac = T / se_hac (as in tab:e1-sim-z).

A shift of z_hac can come from a shift of T or from a dependence between T and its standard error;
the table separates the two.

Input: ``results/e1/e1_sim_raw.csv`` (written by ``experiments/e1_placebo.py --part sim``).
Output: ``paper/tables/manual_e1_sim_stat.tex`` (bare tabular).

Usage (from the repository root)::

    uv run python paper/scripts/e1_sim_stat.py
"""
from __future__ import annotations

import math
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[2]
RAW = ROOT / "results" / "e1" / "e1_sim_raw.csv"
OUT = ROOT / "paper" / "tables" / "manual_e1_sim_stat.tex"
TESTS = {"critic": r"\WC{}", "lrcritic": r"\LRC{}"}
CELLS = (("joint", "joint"), ("indep", "indep."))
COLS = ["synth", "kind", "test", "split", "pvalue_type", "statistic", "se_hac", "z_hac"]


def num(v: float, d: int = 3) -> str:
    if v is None or not math.isfinite(float(v)):
        return "--"
    v = float(v)
    if abs(v) < 0.5 * 10.0 ** (-d):
        v = 0.0  # print 0.000, not -0.000
    return f"{v:.{d}f}"


def main() -> None:
    d = pd.read_csv(RAW, usecols=COLS, low_memory=False)
    d = d[(d["kind"] == "absolute") & (d["split"] == "time_block") & (d["pvalue_type"] == "hac")]
    for c in ("statistic", "se_hac", "z_hac"):
        d[c] = pd.to_numeric(d[c], errors="coerce")
    lines = [
        "% generated by paper/scripts/e1_sim_stat.py from results/e1/e1_sim_raw.csv",
        r"\begin{tabular}{llrrrrrrr}",
        r"\toprule",
        r"Test & $G^*$ & $N$ & mean $T$ (s.e.) & sd $T$ & share $T>0$"
        r" & median $\widehat{\mathrm{se}}_{\mathrm{HAC}}$"
        r" & $\Corr(T,\widehat{\mathrm{se}}_{\mathrm{HAC}})$ & mean $\zhac$ \\",
        r"\midrule",
    ]
    for i, (test, ttex) in enumerate(TESTS.items()):
        if i:
            lines.append(r"\addlinespace[2pt]")
        first = True
        for cell, ctex in CELLS:
            g = d[(d["synth"] == cell) & (d["test"] == test)].dropna(
                subset=["statistic", "se_hac", "z_hac"])
            n = len(g)
            if n == 0:
                continue
            t = g["statistic"].to_numpy(float)
            se = g["se_hac"].to_numpy(float)
            z = g["z_hac"].to_numpy(float)
            sd = float(np.std(t, ddof=1))
            row = [ttex if first else "", ctex, str(n),
                   f"{num(np.mean(t))} ({num(sd / math.sqrt(n))})", num(sd),
                   num(np.mean(t > 0), 2), num(np.median(se)),
                   num(np.corrcoef(t, se)[0, 1], 2), num(np.mean(z), 2)]
            lines.append(" & ".join(row) + r" \\")
            print(cell, test, row[2:])
            first = False
    lines += [r"\bottomrule", r"\end{tabular}", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
