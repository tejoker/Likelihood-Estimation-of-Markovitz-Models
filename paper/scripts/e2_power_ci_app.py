"""Readable appendix versions of the E2 and E2-dep power tables with Wilson intervals (Appendix C).

Reads ``results/e2/e2_rejection.csv`` and ``results/e2dep/e2dep_rejection.csv`` (written by
``experiments/e2_ground_truth.py`` and ``experiments/e2_dependence.py``) and writes

* ``paper/tables/manual_e2_power_ci_app.tex`` (label tab:e2-power-ci) and
* ``paper/tables/manual_e2dep_power_app.tex`` (label tab:e2dep-power):

rejection rates at alpha = 0.05 with Wilson 95% intervals, formatted exactly as in the generated
``e2_power_ci.tex`` / ``e2dep_power.tex`` (``rate [lo, hi]``, 2 decimals), with the family as a
group row and short test labels, so that the tables fit the text width at a readable size (the
generated tables carry long family and oracle labels in their first column and shrink below 6pt).
Marks: dagger = KS not valid (within-window dependence); double dagger = approximate oracle.

Usage (from the repository root)::

    uv run python paper/scripts/e2_power_ci_app.py
"""
from __future__ import annotations

import math
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[2]
TESTS = [("critic", r"\WC{}"), ("lrcritic", r"\LRC{}"), ("c2st", "C2ST"), ("mmd", "MMD"),
         ("sigmmd", r"\SigMMD{}"), ("ks", "KS"), ("oracle", "LR oracle")]
DAG, DDAG = r"$^{\dagger}$", r"$^{\ddagger}$"

E2 = {"src": ROOT / "results" / "e2" / "e2_rejection.csv",
      "out": ROOT / "paper" / "tables" / "manual_e2_power_ci_app.tex",
      "families": [("a", r"(a) volatility level, $\vartheta$: 0, 0.05, 0.1, 0.2, 0.3"),
                   ("b", r"(b) tails, $\nu$: 4, 6, 10, 30, $\infty$"),
                   ("c", r"(c) volatility clustering, $a+b$: 0.98, 0.95, 0.90, 0.80, 0"),
                   ("d", r"(d) jumps, $\vartheta$: 0, 0.25, 0.5, 0.75, 1")],
      "ks_invalid": {"c"}, "oracle_approx": {"c"}}
DEP = {"src": ROOT / "results" / "e2dep" / "e2dep_rejection.csv",
       "out": ROOT / "paper" / "tables" / "manual_e2dep_power_app.tex",
       "families": [("mix", r"(a) window mixture, $\vartheta$: 0, 0.25, 0.5, 0.75, 1"),
                    ("block", r"(b) block length, $L_b$: 20, 10, 5, 2, 1")],
       "ks_invalid": {"mix", "block"}, "oracle_approx": {"mix", "block"}}


def fmt(rate: float, lo: float, hi: float, digits: int = 2) -> str:
    if not math.isfinite(float(rate)):
        return "--"
    return f"{rate:.{digits}f} [{lo:.{digits}f}, {hi:.{digits}f}]"


def build(spec: dict) -> None:
    d = pd.read_csv(spec["src"])
    lines = [r"\begin{tabular}{rlccccc}", r"\toprule",
             r"$n$ & Test & $k=0$ ($H_0$) & $k=1$ & $k=2$ & $k=3$ & $k=4$ \\", r"\midrule"]
    for fi, (fam, title) in enumerate(spec["families"]):
        if fi:
            lines.append(r"\addlinespace[3pt]")
        lines.append(r"\multicolumn{7}{@{}l}{\emph{" + title + r"}} \\")
        for n in sorted(d.loc[d.family == fam, "n"].unique()):
            for ti, (test, lab) in enumerate(TESTS):
                g = d[(d.family == fam) & (d.n == n) & (d.test == test)].set_index("k")
                if len(g) != 5:
                    raise SystemExit(f"missing levels for {fam}/{n}/{test}")
                mark = ""
                if test == "ks" and fam in spec["ks_invalid"]:
                    mark = DAG
                if test == "oracle" and fam in spec["oracle_approx"]:
                    mark = DDAG
                cells = [fmt(g.loc[k, "rej_0.05"], g.loc[k, "lo_0.05"], g.loc[k, "hi_0.05"])
                         for k in range(5)]
                lines.append(f"{n if ti == 0 else ''} & {lab}{mark} & " + " & ".join(cells)
                             + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    spec["out"].parent.mkdir(parents=True, exist_ok=True)
    spec["out"].write_text(f"% generated by paper/scripts/e2_power_ci_app.py from "
                           f"{spec['src'].relative_to(ROOT)}\n" + "\n".join(lines) + "\n",
                           encoding="utf-8")
    print(f"wrote {spec['out']}")


def main() -> None:
    build(E2)
    build(DEP)


if __name__ == "__main__":
    main()
