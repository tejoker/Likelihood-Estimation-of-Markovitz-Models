"""Condensed main-text version of the E2 part f table (Section 5, label tab:e2-llr).

Reads ``results/e2/e2_llr.csv`` (written by ``experiments/e2_ground_truth.py``) and writes
``paper/tables/manual_e2_llr_main.tex``: the same medians and formatted values as the generated
``e2_llr.tex``, with the comparison as a group row and short score labels, so that the table fits
the text width at a readable size.

Usage (from the repository root)::

    uv run python paper/scripts/e2_llr_main.py
"""
from __future__ import annotations

import re
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "results" / "e2" / "e2_llr.csv"
OUT = ROOT / "paper" / "tables" / "manual_e2_llr_main.tex"

COMPARISONS = [("gbm_merton", r"GBM (synthetic) vs Merton (real)"),
               ("garch98_garch90", r"GARCH 0.90 (synthetic) vs GARCH 0.98 (real)")]
SCORES = [("lrcritic", "default", r"\LRC{}: early stopping (test default)"),
          ("lrcritic", "fixed", r"\LRC{}: 1000 steps, lr $10^{-3}$"),
          ("lrcritic", "long_lowlr", r"\LRC{}: 3000 steps, lr $10^{-4}$"),
          ("critic", "default", r"\WC{}: 1000 steps (test default)"),
          ("oracle", "", r"exact $\log(p/q)$")]
COLS = ["Spearman", "Pearson", "Cal. slope", "RMSE", "Accuracy", "Steps"]


def tex_num(s: str) -> str:
    """Typeset a minus sign as math minus; leave everything else as formatted in the CSV."""
    return re.sub(r"(?<![\w.])-(?=\d)", "$-$", str(s))


def main() -> None:
    df = pd.read_csv(SRC, dtype=str).fillna("")
    lines = [
        r"\begin{tabular}{lrrrrrr}",
        r"\toprule",
        r"Score & Spearman & Pearson & Cal.\ slope & RMSE & Accuracy & Steps \\",
        r"\midrule",
    ]
    for ci, (comp, title) in enumerate(COMPARISONS):
        if ci:
            lines.append(r"\addlinespace[3pt]")
        lines.append(r"\multicolumn{7}{@{}l}{\emph{" + title + r"}} \\")
        for score, variant, lab in SCORES:
            sel = df[(df["comparison"] == comp) & (df["score"] == score)
                     & (df["variant"] == variant)]
            if len(sel) != 1:
                raise SystemExit(f"missing row {comp}/{score}/{variant}")
            r = sel.iloc[0]
            if r["reps"] != "20":
                raise SystemExit(f"unexpected replication count for {comp}/{score}/{variant}")
            cells = [tex_num(r[c]) if r[c] != "--" else "--" for c in COLS]
            lines.append(r"\quad " + lab + " & " + " & ".join(cells) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("% generated by paper/scripts/e2_llr_main.py from results/e2/e2_llr.csv\n"
                   + "\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
