"""Condensed main-text version of the E2 part e table (Section 5, label tab:e2-relative-boundary).

Reads ``results/e2/e2_relative.csv`` (written by ``experiments/e2_ground_truth.py``) and writes
``paper/tables/manual_e2_relative_boundary_main.tex``: the same rejection rates and Wilson 95%
intervals as the generated ``e2_relative_boundary.tex`` (3 decimals), with the scenario as a group
row and short generator labels, so that the table fits the text width at a readable size (the
generated table has to be shrunk below 6pt).

Usage (from the repository root)::

    uv run python paper/scripts/e2_relative_boundary_main.py
"""
from __future__ import annotations

import math
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "results" / "e2" / "e2_relative.csv"
OUT = ROOT / "paper" / "tables" / "manual_e2_relative_boundary_main.tex"

GROUPS = [
    (r"$\Pnew=\Ppast$: GARCH 0.98", [("equal", r"boundary: $G\sim\Ppast=\Pnew$")]),
    (r"$\Pnew$: GARCH 0.98, $\Ppast$: GARCH 0.95", [
        ("past", r"boundary: $G\sim\Ppast$"),
        ("new", r"interior: $G\sim\Pnew$"),
        ("garch90", "worse: GARCH 0.90"),
        ("gbm", "worse: GBM"),
        ("resample", r"resample of $\Rpast$, split by source"),
        ("resample_naive", r"resample of $\Rpast$, random split (leakage)"),
    ]),
]
METHODS = ("anchored", "two_critic")
ALPHAS = ("0.05", "0.10")


def num(v: float, d: int = 3) -> str:
    return "--" if v is None or not math.isfinite(float(v)) else f"{float(v):.{d}f}"


def main() -> None:
    df = pd.read_csv(SRC)
    if df["n"].nunique() != 1:
        raise SystemExit("expected a single sample size in e2_relative.csv")
    idx = df.set_index(["G", "method"])
    lines = [
        r"\begin{tabular}{lcccc}",
        r"\toprule",
        r" & \multicolumn{2}{c}{Anchored (permutation)}"
        r" & \multicolumn{2}{c}{Two-critic (paired bootstrap)} \\",
        r"\cmidrule(lr){2-3}\cmidrule(lr){4-5}",
        r"Generator $G$ & $\alpha=0.05$ & $\alpha=0.10$ & $\alpha=0.05$ & $\alpha=0.10$ \\",
        r"\midrule",
    ]
    for gi, (title, rows) in enumerate(GROUPS):
        if gi:
            lines.append(r"\addlinespace[3pt]")
        lines.append(r"\multicolumn{5}{@{}l}{\emph{" + title + r"}} \\")
        for g, lab in rows:
            cells = []
            for m in METHODS:
                r = idx.loc[(g, m)]
                if int(r["n_valid"]) != 200 or int(r["n_nan"]) != 0:
                    raise SystemExit(f"unexpected replication count for {g}/{m}")
                for a in ALPHAS:
                    cells.append(f"{num(r[f'rej_{a}'])} [{num(r[f'lo_{a}'])}, {num(r[f'hi_{a}'])}]")
            lines.append(r"\quad " + lab + " & " + " & ".join(cells) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("% generated by paper/scripts/e2_relative_boundary_main.py from "
                   "results/e2/e2_relative.csv\n" + "\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
