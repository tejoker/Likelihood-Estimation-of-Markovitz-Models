"""Diagnostics of the E1(a) placebo for Appendix C (labels tab:e1-sim-dependence, tab:e1-sim-z).

Reads ``results/e1/e1_dependence.csv`` and ``results/e1/e1_sim_raw.csv`` (both written by
``experiments/e1_placebo.py --part sim``) and writes

* ``paper/tables/manual_e1_sim_dependence.tex``: mean pairwise correlation of daily returns and of
  the rolling 20-day log-volatility for the real panel (TRAIN, TEST) and for the three simulated
  panels of the placebo (R_past*, R_new*, G* in both cells); placebo rows show the mean and the
  interquartile range over the 200 replications;
* ``paper/tables/manual_e1_sim_z.tex``: the Driscoll-Kraay statistic z_hac of the learned tests
  and of the relative tests under the placebo null (time-block split): mean and standard
  deviation over the replications (N(0, 1) if the p-value were calibrated), share above the
  normal 5% critical value 1.645 (the tabulated size), median number of evaluation dates and
  median Bartlett lag of the real (first) sample.

Usage (from the repository root)::

    uv run python paper/scripts/e1_sim_diag.py
"""
from __future__ import annotations

import math
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[2]
DEP = ROOT / "results" / "e1" / "e1_dependence.csv"
RAW = ROOT / "results" / "e1" / "e1_sim_raw.csv"
OUT_DEP = ROOT / "paper" / "tables" / "manual_e1_sim_dependence.tex"
OUT_Z = ROOT / "paper" / "tables" / "manual_e1_sim_z.tex"

SOURCE_TEX = {"real TRAIN": r"real \TRAIN{} (2018--2022)",
              "real TEST": r"real \TEST{} (2023--2025-06-16)",
              "placebo R_past* (TRAIN length)": r"placebo $\Rpast^*$ (\TRAIN{} length)",
              "placebo R_new* (TEST length)": r"placebo $\Rnew^*$ (\TEST{} length)",
              "placebo G*, joint": r"placebo $G^*$, joint",
              "placebo G*, indep": r"placebo $G^*$, indep."}
TEST_TEX = {"critic": r"\WC{}", "lrcritic": r"\LRC{}", "c2st": "C2ST",
            "relative_anchored": "Anchored relative", "relative_two_critic": "Two-critic relative"}
HEADER = "% generated by paper/scripts/e1_sim_diag.py from results/e1/\n"


def num(v: float, d: int = 3) -> str:
    if v is None or not math.isfinite(float(v)):
        return "--"
    v = float(v)
    if abs(v) < 0.5 * 10.0 ** (-d):
        v = 0.0  # print 0.000, not -0.000
    return f"{v:.{d}f}"


def dependence_table() -> None:
    d = pd.read_csv(DEP).set_index("source")
    lines = [r"\begin{tabular}{lrcc}", r"\toprule",
             r"Panel & Replications & Return correlation & Log-volatility correlation \\",
             r"\midrule"]
    for src, tex in SOURCE_TEX.items():
        r = d.loc[src]
        n = int(r["n_reps"])
        if n == 1:
            c1, c2 = num(r["corr_mean"]), num(r["logvol_corr_mean"])
        else:
            c1 = f"{num(r['corr_mean'])} [{num(r['corr_q25'])}, {num(r['corr_q75'])}]"
            c2 = (f"{num(r['logvol_corr_mean'])} [{num(r['logvol_q25'])}, "
                  f"{num(r['logvol_q75'])}]")
        lines.append(f"{tex} & {n} & {c1} & {c2} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    OUT_DEP.write_text(HEADER + "\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT_DEP}")


def z_table() -> None:
    d = pd.read_csv(RAW, low_memory=False)
    sel = d[((d["kind"] == "absolute") & (d["split"] == "time_block")
             & (d["pvalue_type"] == "hac"))
            | ((d["kind"] == "relative") & (d["pvalue_type"] == "hac"))].copy()
    sel["z_hac"] = pd.to_numeric(sel["z_hac"], errors="coerce")
    lines = [r"\begin{tabular}{llrrrrrr}", r"\toprule",
             r"$G^*$ & Test & $N$ & mean $\zhac$ & sd $\zhac$ & share $\zhac>1.645$"
             r" & eval.\ dates & lag $H$ \\", r"\midrule"]
    for cell, ctex in (("joint", "joint"), ("indep", "indep.")):
        first = True
        for test, ttex in TEST_TEX.items():
            g = sel[(sel["synth"] == cell) & (sel["test"] == test)]
            z = g["z_hac"].dropna().to_numpy(float)
            if z.size == 0:
                continue
            row = [ctex if first else "", ttex, str(z.size), num(np.mean(z), 2),
                   num(np.std(z, ddof=1), 2), num(np.mean(z > 1.6448536269514722), 3),
                   num(pd.to_numeric(g["T_eval_x"], errors="coerce").median(), 0),
                   num(pd.to_numeric(g["H_x"], errors="coerce").median(), 0)]
            lines.append(" & ".join(row) + r" \\")
            first = False
        if cell == "joint":
            lines.append(r"\addlinespace[2pt]")
    lines += [r"\bottomrule", r"\end{tabular}"]
    OUT_Z.write_text(HEADER + "\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT_Z}")


def main() -> None:
    OUT_DEP.parent.mkdir(parents=True, exist_ok=True)
    dependence_table()
    z_table()


if __name__ == "__main__":
    main()
